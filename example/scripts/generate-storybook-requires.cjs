const fs = require('fs');
const path = require('path');

const cwd = path.resolve(__dirname, '..');
const configPath = path.resolve(cwd, '.rnstorybook');
const outputPath = path.resolve(configPath, 'storybook.requires.ts');
const mainPath = path.resolve(configPath, 'main.js');
const mainModule = require(mainPath);
const main = mainModule.default ? mainModule.default : mainModule;

function ensureRelativePathHasDot(relativePath) {
  return relativePath.startsWith('.') ? relativePath : `./${relativePath}`;
}

const storyPattern =
  Array.isArray(main.stories) && typeof main.stories[0] === 'string'
    ? main.stories[0]
    : null;

if (!storyPattern) {
  throw new Error(
    'Expected the first Storybook stories entry to be a string glob.'
  );
}

const storyRoot = storyPattern.replace(/\/\*\*\/.*$/, '');
const storyFiles = storyPattern.slice(storyRoot.length + 1);
const resolvedStoryRoot = path.resolve(configPath, storyRoot);
const storyDirectory = path
  .relative(cwd, resolvedStoryRoot)
  .split(path.sep)
  .join('/');
const requireContextPath = ensureRelativePathHasDot(
  path.relative(configPath, resolvedStoryRoot).split(path.sep).join('/')
);
const storiesMatcher = String.raw`^\.(?:(?:^|[\\/]|(?:(?:(?!(?:^|[\\/])\.).)*?)[\\/])(?!\.)(?=.)[^\\/]*?\.stories\.(ts|tsx))$`;

const normalizedStories = `{
    titlePrefix: "",
    directory: "${storyDirectory}",
    files: "${storyFiles}",
    importPathMatcher: /${storiesMatcher}/,
    // @ts-ignore
    req: require.context(
      '${requireContextPath}',
      true,
      /${storiesMatcher}/
    ),
  }`;

const registeredAddons = (main.addons || [])
  .map((addon) => {
    if (typeof addon === 'string') {
      return addon;
    }

    return addon && addon.name ? addon.name : null;
  })
  .filter(Boolean)
  .map((addon) => `import '${addon}/register';`)
  .join('\n');

const fileContent = `/* do not change this file, it is auto generated by storybook. */
import { start, updateView, View } from '@storybook/react-native';

${registeredAddons}

const normalizedStories = [
  ${normalizedStories}
];

declare global {
  var view: View;
  var STORIES: typeof normalizedStories;
}

const annotations = [require('./preview')];

global.STORIES = normalizedStories;

// @ts-ignore
module?.hot?.accept?.();

if (!global.view) {
  global.view = start({
    annotations,
    storyEntries: normalizedStories,
  });
} else {
  updateView(global.view, annotations, normalizedStories);
}

export const view: View = global.view;
`;

fs.writeFileSync(outputPath, fileContent, 'utf8');
